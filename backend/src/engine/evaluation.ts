function squareIndex(square: Square): number {
  const file = square.charCodeAt(0) - "a".charCodeAt(0); // 0-7
  const rank = parseInt(square[1], 10); // 1-8
  // Table arrays are written rank 8 (index 0) -> rank 1 (index 7).
  const row = 8 - rank;
  return row * 8 + file;
}

function pieceSquareValue(piece: PieceSymbol, square: Square, color: Color): number {
  const table = TABLES[piece];
  const idx = color === "w" ? squareIndex(square) : mirror(squareIndex(square));
  return table[idx];
}

function mirror(index: number): number {
  const row = Math.floor(index / 8);
  const col = index % 8;
  const mirroredRow = 7 - row;
  return mirroredRow * 8 + col;
}

/**
 * Static evaluation in centipawns from White's perspective.
 * Positive = White is better, negative = Black is better.
 *
 * This is a material/positional scorer only - it does not check for
 * checkmate, stalemate, or draws. Those are terminal conditions the search
 * (chessEngine.ts) detects itself from the legal-move list it already
 * generates, so this function can stay a cheap, allocation-light leaf
 * evaluator that runs unmodified at every node the search visits.
 */
export function evaluateBoard(game: Chess): number {
  let score = 0;
  const board = game.board();
  for (let row = 0; row < 8; row++) {
    for (let col = 0; col < 8; col++) {
      const cell = board[row][col];
      if (!cell) continue;
      const value = PIECE_VALUES[cell.type] + pieceSquareValue(cell.type, cell.square, cell.color);
      score += cell.color === "w" ? value : -value;
    }
  }

  return score;
}
